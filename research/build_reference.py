def score(values):
    earned = Decimal(0)
    applicable = Decimal(0)
    for (_, _, weight, allowed, maximum), value in zip(CRITERIA, values, strict=True):
        if value not in allowed:
            raise ValueError((value, allowed))
        if value == 'N/A' or weight == 0:
            continue
        applicable += Decimal(weight)
        fraction = (Decimal(value) / Decimal(maximum)) if maximum else Decimal(value == 'Да')
        earned += Decimal(weight) * fraction
    result = (100 * earned / applicable).quantize(Decimal('.01'), rounding=ROUND_HALF_UP) if applicable else None
    return {'earned_before_redistribution': float(earned), 'applicable_weight': int(applicable),
            'total': float(result) if result is not None else None,
            'gross_error': values[7] == 'Да'}

